import { expect, test } from '@playwright/test';

test('built demo: models, two turns, isolated retry and local history', async ({ baseURL, page, context }, info) => {
  const requests: Array<{ route: string; body: { targets?: Array<{ modelId: string; history: Array<{user: string; assistant: string}> }>; target?: {modelId: string; history: unknown[]} } }> = [];
  const external: string[] = [];
  context.on('request', (request) => {
    const url = new URL(request.url());
    if (url.origin !== baseURL) external.push(url.origin);
    if (request.method() === 'POST' && /\/api\/(comparisons|retries)$/.test(url.pathname)) requests.push({ route: url.pathname, body: request.postDataJSON() });
  });
  await context.route('**/*', (route) => new URL(route.request().url()).origin === baseURL ? route.continue() : route.abort());
  await page.goto('/');
  const initialPrompt = 'Когда нужен Redis?';
  const nextPrompt = 'Когда достаточно памяти процесса?';
  const input = page.getByRole('textbox', { name: 'Ваш вопрос' });
  const finished = page.getByText('Сравнение завершено.', { exact: true });
  const ask = async (prompt: string) => {
    await input.fill(prompt);
    await input.press('Enter');
    await expect(finished).toBeVisible();
  };
  const catalog = await (await page.request.get('/api/models')).json();
  expect(catalog.mode).toBe('mock');
  expect(catalog.models).toHaveLength(4);
  await ask(initialPrompt);
  await expect(page.getByRole('heading', { name: 'Демонстрационный ответ' })).toBeVisible();
  await expect(page.getByRole('table')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Скопировать код' })).toBeVisible();
  expect(requests[0]?.body.targets?.map((target) => target.history.length)).toEqual([0, 0]);
  await page.getByRole('button', { name: 'Добавить модель', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: /Ошибка/ }).click();
  await ask(nextPrompt);
  const next = requests[1]?.body.targets;
  expect(next?.map((target) => target.history.length)).toEqual([1, 1, 0]);
  expect(next?.slice(0, 2).map((target) => target.history[0]?.user)).toEqual([initialPrompt, initialPrompt]);
  const retry = page.getByRole('button', { name: 'Повторить ответ' });
  await expect(retry).toBeEnabled();
  const previous = await page.locator('.markdown').allTextContents();
  await retry.click();
  await expect.poll(() => requests.length).toBe(3);
  await expect(retry).toBeEnabled();
  await expect(finished).toBeVisible();
  expect(requests[2]).toMatchObject({ route: '/api/retries', body: { target: { modelId: 'mock-error', history: [] } } });
  expect(await page.locator('.markdown').allTextContents()).toEqual(previous);
  const storage = page.locator('.history-toolbar').getByRole('status', { includeHidden: true });
  await input.fill('Черновик перед перезагрузкой');
  await expect(storage).toHaveText('Сохранено на устройстве');
  await page.reload();
  await expect(input).toHaveValue('Черновик перед перезагрузкой');
  await expect(page.getByText(nextPrompt, { exact: true })).toBeVisible();
  expect(requests).toHaveLength(3);
  await page.getByRole('button', { name: 'Новое сравнение', exact: true }).click();
  await expect(page.getByText(nextPrompt, { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'История', exact: true }).click();
  await page.getByRole('region', { name: 'История бесед' }).getByRole('button', { name: initialPrompt, exact: true }).click();
  await expect(page.getByText(nextPrompt, { exact: true })).toBeVisible();
  await expect(input).toHaveValue('Черновик перед перезагрузкой');
  expect(requests).toHaveLength(3);
  expect(external).toEqual([]);
  await page.screenshot({ path: info.outputPath('demo.png') });
});
